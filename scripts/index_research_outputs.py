"""Index M5 output files once a run crosses the ARIS15-artifact threshold."""

import argparse
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from simready.storage import PROJECT_ROOT


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--study", type=Path, nargs="+", required=True)
    args = parser.parse_args()
    files = set()
    for candidate in args.study:
        study = candidate.resolve()
        if not study.is_relative_to(PROJECT_ROOT) or not study.is_dir():
            raise ValueError("study output index requires a directory inside the project")
        files.update(
            p
            for p in study.rglob("*")
            if p.is_file() and not p.name.endswith((".lock", ".pending"))
        )
    # Preserve earlier indexed studies when adding another run.
    manifest = PROJECT_ROOT / "MANIFEST.md"
    if manifest.exists():
        for line in manifest.read_text().splitlines():
            columns = line.split("|")
            if len(columns) == 7:
                name = columns[3].strip()
                path = (PROJECT_ROOT / name).resolve()
                if path.is_relative_to(PROJECT_ROOT) and path.is_file():
                    files.add(path)
    files.update((PROJECT_ROOT / "refine-logs").glob("*.md"))
    files = sorted(files)
    if len(files) <= 15:
        return
    lines = [
        "# Research Output Manifest",
        "",
        "> Auto-maintained by ARIS skills. Tracks generated research artifacts.",
        "",
        "Generated by `scripts/index_research_outputs.py`. Raw outputs remain gitignored;",
        "this index contains paths, not dataset pixels or model parameters. Content pins",
        "are authoritative in the artifact/evaluation/analysis manifests and stages.json.",
        "",
        "| Timestamp (Asia/Bangkok) | Skill | File | Stage | Description |",
        "|---|---|---|---|---|",
    ]
    for path in files:
        name = path.relative_to(PROJECT_ROOT).as_posix()
        timestamp = datetime.fromtimestamp(path.stat().st_mtime, ZoneInfo("Asia/Bangkok"))
        if name.startswith("refine-logs/"):
            skill, stage, label = "/experiment-plan", "implementation", "frozen plan or tracker"
        elif name.startswith("experiments/m6-benchmark-"):
            skill, stage, label = "local benchmark", "review", "measured shipping output"
        elif "/analysis-" in name:
            skill, stage, label = "/analyze-results", "review", "measured analysis output"
        else:
            skill, stage, label = "/run-experiment", "implementation", "frozen study raw output"
        lines.append(f"| {timestamp:%Y-%m-%d %H:%M:%S} | {skill} | {name} | {stage} | {label} |")
    (PROJECT_ROOT / "MANIFEST.md").write_text("\n".join(lines) + "\n")
    print(f"Indexed {len(files)} research output files")


if __name__ == "__main__":
    main()
